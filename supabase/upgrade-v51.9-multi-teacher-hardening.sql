  );

-- CRM may move an unstarted trial to another teacher. Once the student has
-- real learning history, transfer is deliberately rejected instead of moving
-- historical data across teacher cabinets.
create or replace function public.crm_transfer_unstarted_trial(
  p_lead_id text,
  p_new_teacher uuid
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_student public.students;
  v_lesson public.lessons;
  v_event_key text := 'crm-trial:' || p_lead_id;
  v_has_history boolean := false;
begin
  if p_lead_id is null or btrim(p_lead_id)='' then
    raise exception 'invalid_lead_id';
  end if;

  if not exists(
    select 1 from public.teachers t
    where t.id=p_new_teacher and t.access_enabled=true
  ) then
    raise exception 'target_teacher_unavailable';
  end if;

  select * into v_student
  from public.students
  where crm_lead_id=p_lead_id
  for update;

  if v_student.id is null then
    return jsonb_build_object('ok',true,'changed',false,'reason','student_not_created');
  end if;

  if v_student.teacher_id=p_new_teacher then
    return jsonb_build_object('ok',true,'changed',false,'reason','already_assigned');
  end if;

  select * into v_lesson
  from public.lessons
  where crm_event_key=v_event_key
  for update;

  if v_lesson.id is not null and (
    v_lesson.status in ('in_progress','completed')
    or v_lesson.started_at is not null
    or v_lesson.completed_at is not null
  ) then
    raise exception 'trial_already_started';
  end if;

  select (
    exists(select 1 from public.lessons l
      where l.student_id=v_student.id and (v_lesson.id is null or l.id<>v_lesson.id))
    or exists(select 1 from public.homeworks h where h.student_id=v_student.id)
    or exists(select 1 from public.tests t where t.student_id=v_student.id)
    or exists(select 1 from public.lesson_reports r where r.student_id=v_student.id)
    or exists(select 1 from public.student_goals g where g.student_id=v_student.id)
    or exists(select 1 from public.student_resources r where r.student_id=v_student.id)
    or exists(select 1 from public.student_topic_mastery m where m.student_id=v_student.id)
    or exists(select 1 from public.student_progress_snapshots p where p.student_id=v_student.id)
    or exists(select 1 from public.board_pages b
      where b.student_id=v_student.id
        and (v_lesson.id is null or b.lesson_id is distinct from v_lesson.id))
  ) into v_has_history;

  if v_has_history then
    raise exception 'student_has_learning_history';
  end if;

  update public.students
  set teacher_id=p_new_teacher
  where id=v_student.id;

  if v_lesson.id is not null then
    update public.lessons
    set teacher_id=p_new_teacher,
        topic_id=null,
        schedule_updated_at=now()
    where id=v_lesson.id;

    delete from public.board_pages where lesson_id=v_lesson.id;
    insert into public.board_pages(
      teacher_id,student_id,lesson_id,title,sort_order,elements
    ) values (
      p_new_teacher,v_student.id,v_lesson.id,'Лист 1',0,'[]'::jsonb
    );
  end if;

  return jsonb_build_object(
    'ok',true,
    'changed',true,
    'student_id',v_student.id,
    'lesson_id',v_lesson.id
  );
end;
$$;

revoke all on function public.crm_transfer_unstarted_trial(text,uuid)
  from public, anon, authenticated;
grant execute on function public.crm_transfer_unstarted_trial(text,uuid)
  to service_role;

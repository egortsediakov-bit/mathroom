-- Mathroom v51.9 — multi-teacher security hardening
-- Applied to production on 2026-10-18.
-- Protects admin-controlled teacher access, scopes task-bank sources per teacher,
-- records access changes, and makes CRM trial teacher reassignment safe.

-- Teacher rows are admin/service-role managed. Teachers may read their own row,
-- but must not be able to flip access_enabled or crm_teacher_key themselves.
drop policy if exists teacher_self_update on public.teachers;
revoke insert, update, delete on table public.teachers from anon, authenticated;

-- Admin-only audit trail. Passwords are never stored here.
create table if not exists public.teacher_access_audit (
  id bigint generated by default as identity primary key,
  teacher_id uuid references public.teachers(id) on delete set null,
  teacher_key text not null,
  action text not null check (action in (
    'access_created',
    'email_changed',
    'password_reset',
    'access_disabled',
    'access_enabled'
  )),
  email text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.teacher_access_audit enable row level security;
revoke all on table public.teacher_access_audit from anon, authenticated;
create index if not exists teacher_access_audit_teacher_created_idx
  on public.teacher_access_audit(teacher_id, created_at desc);
create index if not exists teacher_access_audit_created_idx
  on public.teacher_access_audit(created_at desc);

-- Source metadata for the OCR/task-bank pipeline is tenant-owned.
-- A NULL teacher_id is reserved for immutable shared catalog rows.
alter table public.task_bank_sources
  add column if not exists teacher_id uuid references public.teachers(id) on delete cascade;

update public.task_bank_sources s
set teacher_id=b.teacher_id
from public.textbooks b
where s.teacher_id is null
  and s.meta ? 'textbook_id'
  and s.meta->>'textbook_id'=b.id::text;

update public.task_bank_sources s
set teacher_id=t.id
from public.teachers t
where s.teacher_id is null
  and s.storage_bucket='textbooks'
  and split_part(coalesce(s.storage_path,''),'/',1)=t.id::text;

alter table public.task_bank_sources
  drop constraint if exists task_bank_sources_external_key_key;

create unique index if not exists task_bank_sources_owner_external_key_uidx
  on public.task_bank_sources(teacher_id, external_key)
  where teacher_id is not null;

create unique index if not exists task_bank_sources_shared_external_key_uidx
  on public.task_bank_sources(external_key)
  where teacher_id is null;


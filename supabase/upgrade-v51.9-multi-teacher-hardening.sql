create policy mathroom_books_teacher_select
  on storage.objects for select to authenticated
  using (
    bucket_id='mathroom-books'
    and (storage.foldername(name))[1]=auth.uid()::text
  );
create policy mathroom_books_teacher_insert
  on storage.objects for insert to authenticated
  with check (
    bucket_id='mathroom-books'
    and (storage.foldername(name))[1]=auth.uid()::text
  );
create policy mathroom_books_teacher_update
  on storage.objects for update to authenticated
  using (
    bucket_id='mathroom-books'
    and (storage.foldername(name))[1]=auth.uid()::text
  )
  with check (
    bucket_id='mathroom-books'
    and (storage.foldername(name))[1]=auth.uid()::text
  );
